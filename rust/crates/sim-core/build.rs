//! Embeds the deck plan files (`data/plans/*.toml`) in the binary: `plans_data::FILES`, one (file stem, text) pair per
//! file, sorted by name. A new deck's plan file is picked up by the next build with no Rust change.

use std::fmt::Write;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../../data/plans");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|p| p.extension().is_some_and(|x| x == "toml"))
                .map(|p| (p.file_stem().unwrap().to_string_lossy().into_owned(), p))
                .collect()
        })
        .unwrap_or_default();
    files.sort();
    let mut out = String::from("/// the plan files, (file stem, text), sorted by name (generated by build.rs)\n");
    out.push_str("pub const FILES: &[(&str, &str)] = &[\n");
    for (stem, p) in &files {
        let abs = p.canonicalize().unwrap();
        writeln!(out, "    ({stem:?}, include_str!({:?})),", abs.display().to_string()).unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("plan_files.rs");
    std::fs::write(dest, out).unwrap();
}
